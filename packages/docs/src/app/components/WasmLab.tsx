'use client';

import { useEffect, useRef, useState } from 'react';

type Stage = 'download' | 'compile' | 'initialize' | 'compute';
const stages: [Stage, string][] = [
  ['download', 'Fetch'],
  ['compile', 'Compile'],
  ['initialize', 'Initialize'],
  ['compute', 'Compute'],
];

export function WasmLab() {
  const canvas = useRef<HTMLCanvasElement>(null);
  const worker = useRef<Worker | null>(null);
  const timer = useRef<ReturnType<typeof setTimeout> | null>(null);
  const busyRef = useRef(false);
  const seed = useRef(0);
  const [busy, setBusy] = useState(false);
  const [ready, setReady] = useState(false);
  const [active, setActive] = useState<Stage>();
  const [times, setTimes] = useState<Partial<Record<Stage, number>>>({});
  const [result, setResult] = useState<{ checksum: number; size: number }>();
  const [error, setError] = useState('');

  function stop() {
    if (timer.current) clearTimeout(timer.current);
    timer.current = null;
    worker.current?.terminate();
    worker.current = null;
    busyRef.current = false;
  }

  useEffect(() => () => stop(), []);

  function reset() {
    stop();
    seed.current = 0;
    setBusy(false);
    setReady(false);
    setActive(undefined);
    setTimes({});
    setResult(undefined);
    setError('');
    canvas.current?.getContext('2d')?.clearRect(0, 0, 640, 420);
  }

  function run(type: 'prepare' | 'render') {
    if (busyRef.current) return;
    busyRef.current = true;
    setBusy(true);
    setError('');
    if (type === 'render') setTimes(current => ({ ...current, compute: undefined }));
    function fail(message: string) {
      stop();
      setBusy(false);
      setReady(false);
      setActive(undefined);
      setTimes({});
      setError(message);
    }
    try {
      if (!worker.current) {
        const instance = new Worker('/vooya/field-worker.mjs', { type: 'module' });
        worker.current = instance;
        instance.onmessage = ({ data }) => {
          if (worker.current !== instance) return;
          if (data.type === 'stage') {
            setActive(data.name);
            if (typeof data.ms === 'number')
              setTimes(current => ({ ...current, [data.name]: data.ms }));
          } else if (data.type === 'error') {
            fail(data.message);
          } else if (data.type === 'ready' || data.type === 'result') {
            if (timer.current) clearTimeout(timer.current);
            timer.current = null;
            busyRef.current = false;
            setBusy(false);
            setReady(true);
            setActive(undefined);
            if (data.type === 'result') {
              canvas.current
                ?.getContext('2d')
                ?.putImageData(new ImageData(data.pixels, 640, 420), 0, 0);
              setResult({ checksum: data.checksum, size: data.size });
            }
          }
        };
        instance.onerror = () => fail('The worker could not start. Reset and try again.');
        instance.onmessageerror = () =>
          fail('The worker response could not be read. Please try again.');
      }
      timer.current = setTimeout(
        () => fail('Preparation timed out after 30 seconds. Please try again.'),
        30_000
      );
      worker.current.postMessage({ type, seed: seed.current });
      if (type === 'render') seed.current += 1;
    } catch (cause) {
      fail(cause instanceof Error ? cause.message : String(cause));
    }
  }

  return (
    <div className="wasm-lab" id="lab">
      <div className="lab-title">
        <span>
          <i /> COMPUTE LAB
        </span>
        <span>RUST × VOOYA</span>
      </div>
      <div className="field-viewport">
        <canvas
          ref={canvas}
          width={640}
          height={420}
          aria-label="Julia fractal generated by Rust in a Web Worker"
        />
        {!result && (
          <div className="field-placeholder">
            <div className="field-rings" aria-hidden="true">
              <i />
              <i />
              <i />
              <i />
            </div>
            <span>{busy ? 'Preparing your compute engine…' : 'A little room for heavy work.'}</span>
            <small>{busy ? 'The page stays yours.' : 'Run the field to bring it to life.'}</small>
          </div>
        )}
        <div className="field-caption">
          <span>JULIA FIELD / 640 × 420</span>
          <span>{result ? `CHECKSUM ${result.checksum}` : 'ON-DEMAND WASM'}</span>
        </div>
      </div>
      <ol className="lab-stages" aria-label="WASM lifecycle timings">
        {stages.map(([key, label], index) => (
          <li
            key={key}
            className={active === key ? 'active' : times[key] !== undefined ? 'complete' : ''}
          >
            <span>
              <small>0{index + 1}</small> {label}
            </span>
            <strong>
              {times[key] === undefined
                ? active === key
                  ? '…'
                  : '—'
                : `${times[key]!.toFixed(1)} ms`}
            </strong>
          </li>
        ))}
      </ol>
      <div className="lab-controls">
        <button className="run-field" onClick={() => run('render')} disabled={busy}>
          {busy ? 'Working…' : result ? 'Run another field ↗' : 'Run Rust field ↗'}
        </button>
        <button onClick={() => run('prepare')} disabled={busy || ready}>
          {ready ? 'WASM ready' : 'Prepare WASM'}
        </button>
        <button onClick={reset} aria-label="Reset WASM session">
          Reset
        </button>
      </div>
      <p className="lab-status" role="status">
        {error ||
          (busy
            ? `Worker is ${active ?? 'starting'}…`
            : ready
              ? `Module retained for the next run.${result ? ` ${(result.size / 1024).toFixed(0)} KB WASM.` : ''}`
              : 'No WASM requested until you choose to run or prepare.')}
      </p>
      <p className="lab-footnote">
        Vooya Rust Store · dedicated module Worker · experimental bridge
      </p>
    </div>
  );
}
