import { buildApplication } from '@vooya/provider-rust';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const applicationRoot = fileURLToPath(new URL('../wasm', import.meta.url));
const output = fileURLToPath(new URL('../public/vooya', import.meta.url));
const workspacePath = `${applicationRoot}/.vooya/build`;
mkdirSync(workspacePath, { recursive: true });
copyFileSync(`${applicationRoot}/Cargo.lock`, `${workspacePath}/Cargo.lock`);
const artifact = buildApplication({
  applicationRoot,
  workspacePath,
  framework: 'react',
  buildMode: 'production',
});
mkdirSync(output, { recursive: true });
// Keep the generated binding's fallback URL consistent with the published asset.
writeFileSync(
  `${output}/field.mjs`,
  artifact.javascript.code
    .replace(
      '/* @ts-self-types="./vooya_app.d.ts" */',
      '// Generated by @vooya/provider-rust. Run pnpm --filter docs build:wasm to update.'
    )
    .replace(
      "new URL('vooya_app_bg.wasm', import.meta.url)",
      "new URL('field.wasm', import.meta.url)"
    )
);
writeFileSync(`${output}/field.wasm`, artifact.wasm.bytes);
const files = [
  'wasm/src/Field.rs',
  'wasm/Cargo.lock',
  'scripts/build-wasm.mjs',
  'public/vooya/field.mjs',
  'public/vooya/field.wasm',
];
const sha256 = Object.fromEntries(
  files.map(path => [
    path,
    createHash('sha256')
      .update(readFileSync(new URL(`../${path}`, import.meta.url)))
      .digest('hex'),
  ])
);
writeFileSync(
  `${output}/manifest.json`,
  JSON.stringify({ provider: '0.2.0-alpha.0', sha256 }, null, 2) + '\n'
);
console.log(`Built Vooya field: ${artifact.wasm.bytes.length} WASM bytes`);
